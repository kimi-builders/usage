import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = (path) => readFileSync(resolve(root, path), 'utf8');
const targets = ['THIRD_PARTY_LICENSES.txt', 'dashboard/public/THIRD_PARTY_LICENSES.txt'];
const bundled = ['@fontsource/jetbrains-mono', '@lobehub/icons-static-svg', 'html-to-image', 'lucide-react', 'react', 'react-dom', 'scheduler', 'vite'];
const cleanLicenseText = (value) => value.trim().replace(/[ \t]+$/gm, '');

export function thirdPartyLicenses() {
  const lock = JSON.parse(read('dashboard/package-lock.json'));
  for (const name of Object.keys(JSON.parse(read('dashboard/package.json')).dependencies || {})) {
    if (!bundled.includes(name) && name !== '@vitejs/plugin-react') throw new Error(`Review license coverage for new dashboard dependency: ${name}`);
  }
  const sections = bundled.map((name) => {
    const base = `dashboard/node_modules/${name}`;
    const manifest = JSON.parse(read(`${base}/package.json`));
    if (manifest.version !== lock.packages[`node_modules/${name}`]?.version) throw new Error(`Installed license version differs from lockfile: ${name}`);
    const license = name === '@lobehub/icons-static-svg' ? read('licenses/lobehub-icons-MIT.txt') : read(`${base}/${name === 'vite' ? 'LICENSE.md' : 'LICENSE'}`);
    // The distributed font's name table includes this copyright separately
    // from the Fontsource package license. Preserve both notices.
    const fontCopyright = name === '@fontsource/jetbrains-mono'
      ? 'Copyright 2020 The JetBrains Mono Project Authors (https://github.com/JetBrains/JetBrainsMono)\n\n' : '';
    return `${name} ${manifest.version}\n${'='.repeat(72)}\n${fontCopyright}${cleanLicenseText(license)}\n`;
  });
  for (const [name, path] of [['CodexBar adaptations', 'licenses/CodexBar-MIT.txt'], ['Vibe Usage adaptations', 'licenses/vibe-usage-MIT.txt']]) {
    sections.push(`${name}\n${'='.repeat(72)}\n${cleanLicenseText(read(path))}\n`);
  }
  return `THIRD-PARTY LICENSE TEXTS\nGenerated by scripts/third-party-licenses.mjs. See NOTICE for provenance.\n\n${sections.join('\n').trimEnd()}\n`;
}

export function checkThirdPartyLicenses() {
  const expected = thirdPartyLicenses();
  for (const target of [...targets, 'dashboard/dist/client/THIRD_PARTY_LICENSES.txt']) {
    if (read(target) !== expected) throw new Error(`Missing or stale third-party license text: ${target}. Rebuild the dashboard.`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) checkThirdPartyLicenses();
  else for (const target of targets) writeFileSync(resolve(root, target), thirdPartyLicenses());
}
